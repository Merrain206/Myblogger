export function getCityInfo(cityName: string): CityInfo | undefined {
  return CITIES[cityName];
}

export function getProvinces(): string[] {
  const set = new Set<string>();
  Object.values(CITIES).forEach((c) => set.add(c.province));
  return Array.from(set).sort();
}

export function getCitiesByProvince(province: string): string[] {
  return Object.entries(CITIES)
    .filter(([, info]) => info.province === province)
    .map(([name]) => name)
    .sort();
}
